  /* ---------- the whole export (one zip) ---------- */
  // opts: { word, latex, key, retest }  ->  Uint8Array (zip)
  function exportAll(doc, imgs, opts, retestJson, warn) {
    const files = [], base = safe(doc.title);
    for (const v of doc.versions) {
      const stem = base + '-Version-' + v.label;
      if (opts.word) { files.push({ name: 'Word/' + stem + '.docx', data: docx(doc, v, imgs, false, warn) }); if (opts.key) files.push({ name: 'Word/' + stem + '-KEY.docx', data: docx(doc, v, imgs, true, warn) }); }
      if (opts.latex) {
        files.push({ name: 'LaTeX/' + stem + '.tex', data: latexFor(doc, v, false) });
        if (opts.key) files.push({ name: 'LaTeX/' + stem + '-KEY.tex', data: latexFor(doc, v, true) });
        v.questions.forEach((q) => (q.graphs || []).forEach((g, gi) => { const im = imgs && imgs[imgKey(v, q, gi)]; if (im) files.push({ name: 'LaTeX/figures/' + imgKey(v, q, gi) + '.png', data: im.bytes }); }));
      }
    }
    if (opts.retest && retestJson) files.push({ name: base + '.reteach-test.json', data: retestJson });
    return zip(files);
  }

  return { zip, crc32, omml, docx, latexFor, texRich, exportAll, imgKey, safe };
